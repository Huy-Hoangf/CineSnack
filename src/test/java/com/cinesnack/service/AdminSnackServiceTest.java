package com.cinesnack.service;

import static org.junit.jupiter.api.Assertions.*;

import com.cinesnack.catalog.repository.AdminSnackRepository;
import com.cinesnack.catalog.service.AdminSnackService;
import java.math.BigDecimal;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;

class AdminSnackServiceTest {

    private JdbcTemplate database() {
        var db = new JdbcTemplate(
            new DriverManagerDataSource(
                "jdbc:h2:mem:" +
                    UUID.randomUUID() +
                    ";MODE=MSSQLServer;DB_CLOSE_DELAY=-1",
                "sa",
                ""
            )
        );
        db.execute(
            "CREATE TABLE SAN_PHAM(san_pham_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ten_san_pham VARCHAR(100) NOT NULL,loai_san_pham VARCHAR(20) NOT NULL,gia_ban DECIMAL(12,2) NOT NULL,trang_thai VARCHAR(20) NOT NULL)"
        );
        db.execute(
            "CREATE TABLE COMBO(combo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ten_combo VARCHAR(100) NOT NULL,gia_ban DECIMAL(12,2) NOT NULL,trang_thai VARCHAR(20) NOT NULL)"
        );
        db.execute(
            "CREATE TABLE COMBO_SAN_PHAM(combo_id BIGINT REFERENCES COMBO(combo_id),san_pham_id BIGINT REFERENCES SAN_PHAM(san_pham_id),so_luong INT)"
        );
        db.execute(
            "CREATE TABLE CHI_TIET_HOA_DON_BONG_NUOC(san_pham_id BIGINT REFERENCES SAN_PHAM(san_pham_id),combo_id BIGINT REFERENCES COMBO(combo_id))"
        );
        return db;
    }

    @Test
    void createsEditsAndDeletesProductAndCombo() {
        var db = database();
        var service = new AdminSnackService(new AdminSnackRepository(db));
        var product = service.create(
            true,
            "  Bắp lớn  ",
            "BAP",
            new BigDecimal("35000"),
            "HOAT_DONG"
        );
        var combo = service.create(
            false,
            "Combo đôi",
            null,
            new BigDecimal("99000"),
            "HOAT_DONG"
        );

        assertEquals("Bắp lớn", product.name());
        assertEquals("BAP", product.productType());
        assertEquals("Combo đôi", combo.name());
        assertEquals(2, service.list().size());

        var changed = service.update(
            true,
            product.id(),
            "Nước lớn",
            "NUOC",
            new BigDecimal("40000"),
            "NGUNG_HOAT_DONG"
        );
        assertEquals("Nước lớn", changed.name());
        assertEquals("NUOC", changed.productType());
        assertEquals("NGUNG_HOAT_DONG", changed.status());
        assertEquals(
            "Combo đôi",
            service
                .update(
                    false,
                    combo.id(),
                    null,
                    null,
                    new BigDecimal("100000"),
                    "HOAT_DONG"
                )
                .name()
        );

        service.delete(false, combo.id());
        service.delete(true, product.id());
        assertTrue(service.list().isEmpty());
    }

    @Test
    void refusesToDeleteSoldItemsOrProductsInsideCombos() {
        var db = database();
        var service = new AdminSnackService(new AdminSnackRepository(db));
        var product = service.create(
            true,
            "Bắp",
            "BAP",
            new BigDecimal("30000"),
            "HOAT_DONG"
        );
        var combo = service.create(
            false,
            "Combo",
            null,
            new BigDecimal("50000"),
            "HOAT_DONG"
        );
        db.update(
            "INSERT INTO COMBO_SAN_PHAM VALUES(?,?,1)",
            combo.id(),
            product.id()
        );

        var productError = assertThrows(ResponseStatusException.class, () ->
            service.delete(true, product.id())
        );
        assertEquals(HttpStatus.CONFLICT, productError.getStatusCode());
        db.update(
            "INSERT INTO CHI_TIET_HOA_DON_BONG_NUOC VALUES(NULL,?)",
            combo.id()
        );
        var comboError = assertThrows(ResponseStatusException.class, () ->
            service.delete(false, combo.id())
        );
        assertEquals(HttpStatus.CONFLICT, comboError.getStatusCode());
        assertEquals(2, service.list().size());
    }

    @Test
    void rejectsBlankNamesAndMissingProductType() {
        var service = new AdminSnackService(
            new AdminSnackRepository(database())
        );
        assertEquals(
            HttpStatus.BAD_REQUEST,
            assertThrows(ResponseStatusException.class, () ->
                service.create(true, "   ", "BAP", BigDecimal.ONE, "HOAT_DONG")
            ).getStatusCode()
        );
        assertEquals(
            HttpStatus.BAD_REQUEST,
            assertThrows(ResponseStatusException.class, () ->
                service.create(true, "Bắp", null, BigDecimal.ONE, "HOAT_DONG")
            ).getStatusCode()
        );
    }
}
