package com.cinesnack.repository;

import static org.junit.jupiter.api.Assertions.*;

import com.cinesnack.account.repository.AdminStaffRepository;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class AdminStaffRepositoryTest {

    @Test
    void managesStaffButNeverChangesCustomerOrAdminStatus() {
        var db = new JdbcTemplate(
            new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1",
                "sa",
                ""
            )
        );
        db.execute(
            "CREATE TABLE NGUOI_DUNG(nguoi_dung_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ho_ten VARCHAR(100),email VARCHAR(150) UNIQUE,mat_khau_hash VARCHAR(255),vai_tro VARCHAR(20),trang_thai VARCHAR(20))"
        );
        db.update(
            "INSERT INTO NGUOI_DUNG(ho_ten,email,mat_khau_hash,vai_tro,trang_thai) VALUES('Khach','guest','x','KHACH_HANG','HOAT_DONG')"
        );
        var repo = new AdminStaffRepository(db);
        repo.create(
            "Nhan vien",
            "staff@example.com",
            "bcrypt-hash",
            "NHAN_VIEN"
        );
        var staff = repo.byEmail("staff@example.com");
        assertEquals("NHAN_VIEN", staff.role());
        assertEquals(
            "bcrypt-hash",
            db.queryForObject(
                "SELECT mat_khau_hash FROM NGUOI_DUNG WHERE email='staff@example.com'",
                String.class
            )
        );
        assertEquals(1, repo.status(staff.id(), "NGUNG_HOAT_DONG"));
        assertEquals("NGUNG_HOAT_DONG", repo.byId(staff.id()).status());
        assertEquals(0, repo.status(1, "NGUNG_HOAT_DONG"));
    }
}
